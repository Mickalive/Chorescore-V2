  it('F3-AUDIT: All images are valid PNGs with minimum size (non-trivial content)', () => {
    const pngFiles = fs.readdirSync(EVIDENCE_DIR).filter(f => f.endsWith('.png'));

    for (const file of pngFiles) {
      const filePath = path.join(EVIDENCE_DIR, file);
      const stats = fs.statSync(filePath);
      expect(stats.size).toBeGreaterThanOrEqual(MIN_IMAGE_BYTES);

      // Verify PNG magic bytes
      const buffer = Buffer.alloc(8);
      const fd = fs.openSync(filePath, 'r');
      fs.readSync(fd, buffer, 0, 8, 0);
      fs.closeSync(fd);
      expect(buffer[0]).toBe(0x89); // PNG signature byte 1
      expect(buffer[1]).toBe(0x50); // 'P'
      expect(buffer[2]).toBe(0x4e); // 'N'
      expect(buffer[3]).toBe(0x47); // 'G'
    }
  });

